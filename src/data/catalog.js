export const findRayon = (slug) => RAYONS.find((r) => r.slug === slug);

export const findProduct = (rayonSlug, productSlug) =>
  findRayon(rayonSlug)?.products.find((p) => p.slug === productSlug);

export const allProducts = () =>
  RAYONS.flatMap((r) => r.products.map((p) => ({ ...p, rayon: r })));

export const formatPrice = (n) =>
  new Intl.NumberFormat('fr-FR', { style: 'currency', currency: 'EUR' }).format(n);
